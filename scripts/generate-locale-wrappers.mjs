// Generates the bare (no-locale-prefix) mirror of every pages/[lang]/**
// page, so the default locale — which stays unprefixed in the URL (see
// src/lib/i18n/locale-path.ts) — has a REAL Next.js route matching that
// bare URL. Without this, Next's client-side router has only the
// "/[lang]/..." route registered; a bare URL structurally can't match
// that pattern, so every Link navigation to a default-locale page falls
// back to a full browser reload instead of a soft transition.
//
// Runs via the "prebuild" npm hook, same as generate-htaccess.mjs — these
// wrapper files are generated output, not hand-maintained source. Add a
// new page under pages/[lang]/ and its bare twin appears automatically on
// the next build; nothing to remember, nothing to keep in sync by hand.
//
// Each wrapper just re-exports the real page's default export, and (if
// the real page has one) a getServerSideProps that resolves the current
// admin-configured default locale PER REQUEST via fetchDefaultLocale() —
// same helper proxy.ts already uses — and forwards it as params.lang, so
// this stays request-time-flexible (no rebuild needed when the admin
// changes the default locale). Under SEO=false (static export), the real
// page has no getServerSideProps at all (see siteConfig.seoEnabled
// checks throughout pages/[lang]/**), so neither does its wrapper — it
// exports as its own plain static page, same as the [lang] version,
// with data fetched client-side same as today.
import { readdirSync, statSync, writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { join, dirname, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import nextEnv from "@next/env";

const { loadEnvConfig } = nextEnv;

const rootDir = fileURLToPath(new URL("..", import.meta.url));
loadEnvConfig(rootDir);

const langDir = join(rootDir, "pages", "[lang]");
const pagesDir = join(rootDir, "pages");

function walk(dir, files = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (statSync(full).isDirectory()) walk(full, files);
    else if (entry.name.endsWith(".tsx")) files.push(full);
  }
  return files;
}

const sourceFiles = walk(langDir);

for (const sourceFile of sourceFiles) {
  const relPath = relative(langDir, sourceFile);
  const targetFile = join(pagesDir, relPath);
  const targetDir = dirname(targetFile);
  mkdirSync(targetDir, { recursive: true });

  const sourceNoExt = sourceFile.replace(/\.tsx$/, "");
  let importPath = relative(targetDir, sourceNoExt).split(sep).join("/");
  if (!importPath.startsWith(".")) importPath = `./${importPath}`;

  const hasGetServerSideProps = readFileSync(sourceFile, "utf8").includes("getServerSideProps");

  const content = hasGetServerSideProps
    ? `// AUTO-GENERATED by scripts/generate-locale-wrappers.mjs — do not edit by
// hand, it gets overwritten on every build. Edit pages/[lang]/${relPath} instead.
import LangPage, { getServerSideProps as getLangProps } from "${importPath}";
import type { GetServerSideProps } from "next";
import { fetchDefaultLocale } from "@/lib/i18n/language-list";

export default LangPage;

export const getServerSideProps: GetServerSideProps | undefined = getLangProps
  ? async (context) => {
      const lang = await fetchDefaultLocale();
      return (getLangProps as GetServerSideProps)({ ...context, params: { ...context.params, lang } });
    }
  : undefined;
`
    : `// AUTO-GENERATED by scripts/generate-locale-wrappers.mjs — do not edit by
// hand, it gets overwritten on every build. Edit pages/[lang]/${relPath} instead.
export { default } from "${importPath}";
`;

  writeFileSync(targetFile, content);
}

console.log(`Generated ${sourceFiles.length} locale wrapper page(s) under pages/`);

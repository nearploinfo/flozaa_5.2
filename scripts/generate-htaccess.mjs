// Generates public/.htaccess for whichever deploy target NEXT_PUBLIC_SEO
// selects. Runs automatically via the "prebuild" npm lifecycle hook so it's
// always in sync before `next build` copies public/ into the build output
// (out/ for SEO=false, .next/ for SEO=true).
//
// SEO=true (standalone/VPS): Apache still fronts this deploy — a PM2-managed
// `next start` Node process listens on a fixed port behind it — so it needs
// its own .htaccess too, just a reverse-proxy one instead of a static-file
// rewrite one. Pass the port as `node scripts/generate-htaccess.mjs <port>`
// or HTACCESS_PROXY_PORT; defaults to 8001 (this deploy's actual PM2 port).
//
// SEO=false (static export -> out/): Pages Router's Automatic Static
// Optimization means every [lang]-scoped route is built ONCE, as a literal
// "[lang]" folder shared across every admin-configured locale — not one
// copy per locale.
//
// Routes with a real dynamic segment (no getServerSideProps/getStaticProps
// — the segment is genuinely unbounded, e.g. real slugs from the backend)
// export as a literal bracket-named file (e.g. "[...slug].html") that must
// catch every real value for that segment. Add a route here whenever a new
// such page is created (see the corresponding pages/[lang]/**/*.tsx for the
// pattern this mirrors).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import nextEnv from "@next/env";
const { loadEnvConfig } = nextEnv;

// This runs as a standalone Node script (prebuild hook), not inside `next
// build`/`next dev` — Next normally loads .env.local etc. itself before
// evaluating next.config.ts, but nothing does that here, so
// NEXT_PUBLIC_SEO always read as unset (-> seoEnabled defaults true)
// regardless of .env.local. Load it the same way Next itself does.
loadEnvConfig(fileURLToPath(new URL("..", import.meta.url)));

const DEFAULT_LOCALE = "en";
const seoEnabled = process.env.NEXT_PUBLIC_SEO !== "false";
const proxyPort = process.argv[2] || process.env.HTACCESS_PROXY_PORT || "8001";

const DYNAMIC_SEGMENT_ROUTES = [
  { prefix: "service-details", file: "[...slug].html" },
  { prefix: "provider-details", file: "[...slug].html" },
  { prefix: "booking", file: "[...slug].html" },
  { prefix: "my-service-request-details", file: "[...slug].html" },
  { prefix: "blog-details", file: "[slug].html" },
  { prefix: "custom-page", file: "[slug].html" },
  // Optional catch-all ([[...chatId]]) — unlike the others, "/chats" alone
  // (no id) is a real, valid destination (the thread list), so its rule
  // must match a bare prefix too, not just "prefix/something".
  { prefix: "chats", file: "[[...chatId]].html", optional: true },
];

// `[`/`]` are NOT special in a RewriteRule's substitution (target) string —
// only in the pattern, where they're a regex char class. Percent-encoding
// them here (%5B/%5D) actively breaks the rule instead: `%5` in a
// substitution is mod_rewrite's RewriteCond backreference syntax, so
// `%5Blang%5D.html` doesn't decode to "[lang].html" at all — it evaluates
// to the (empty, undefined) backreference %5 followed by the literal "B",
// then "lang", then backreference %5 again followed by literal "D" —
// producing the literal filename "BlangD.html", which doesn't exist, so
// every one of these rules 404s. Verified with `LogLevel rewrite:trace6`
// against a real Apache instance. Literal brackets in the target are safe.
const dynamicSegmentRules = DYNAMIC_SEGMENT_ROUTES.map(
  ({ prefix, file, optional }) =>
    `RewriteRule ^[a-z]{2}(-[A-Z]{2})?/${prefix}${optional ? "(/.*)?" : "/.*"}$ /[lang]/${prefix}/${file} [L]`
).join("\n");

// Same routes again, without a locale prefix — the default locale stays
// bare everywhere (see localizePath), so e.g. "/service-details/foo" needs
// its own rule; it won't match the locale-prefixed ones above. Target is
// the BARE export (see scripts/generate-locale-wrappers.mjs — pages/service-
// details/[...slug].tsx etc.), not the shared /[lang]/... file: that page's
// own registered route has no "lang" segment, so it structurally matches
// the real bare URL. Pointing this at the /[lang]/... file instead would
// serve a page whose own route DOES require a lang segment the real URL
// doesn't have — Next's hydration-time query-param correction then fails
// to match, and falls back toward the route's literal placeholder text
// (e.g. slug becomes the literal string "[...slug]") instead of the real
// value, breaking every client-side data fetch keyed off that param.
const bareDynamicSegmentRules = DYNAMIC_SEGMENT_ROUTES.map(
  ({ prefix, file, optional }) => `RewriteRule ^${prefix}${optional ? "(/.*)?" : "/.*"}$ /${prefix}/${file} [L]`
).join("\n");

const staticExportContent = `# Apache config for the static export build (\`SEO=false\` -> \`npm run build\` -> out/).
# Generated by scripts/generate-htaccess.mjs (runs via the "prebuild" npm hook) —
# edit that script, not this file directly, it gets overwritten on every build.
# Not used for the standalone/VPS build (SEO=true) — see the other branch in
# that script for the reverse-proxy .htaccess that build gets instead.

Options -Indexes -MultiViews
RewriteEngine On
RewriteBase /

# Root "/" needs NO rewrite: the bare wrapper (see
# scripts/generate-locale-wrappers.mjs) already exports a real, static
# "index.html" for the default locale with no dynamic "[lang]" segment —
# Apache's own DirectoryIndex serves it directly. Rewriting "/" to the
# shared "/[lang].html" template instead (as this used to do) serves a
# page whose registered route IS "/[lang]" while the live URL is "/" —
# Next's client router can't reconcile that on hydrate (throws "The
# provided as value (/) is incompatible with the href value (/[lang])"),
# and leaves router state stuck with asPath as the literal "/[lang]" —
# which silently breaks anything keyed off the real pathname (e.g. the
# bottom nav's exact-path match in navigation-config.ts).

# Serve a real file exactly as requested (e.g. /_next/static/..., /favicon.ico).
RewriteCond %{REQUEST_FILENAME} -f
RewriteRule ^ - [L]

# Prefer a route's own flat "<path>.html" export over letting Apache try to
# list/serve the same-named directory of per-route asset chunks — only
# matters for a route that ships real per-locale content (none currently;
# kept generic in case one shows up again).
RewriteCond %{DOCUMENT_ROOT}/$1.html -f
RewriteRule ^(.*[^/])/?$ $1.html [L]

# Routes with a real (unbounded, backend-driven) dynamic segment -> the
# shared build's literal bracket-named file. The client reads the real
# locale and slug from the live browser URL, not this rewrite target.
${dynamicSegmentRules}

# Same dynamic-segment routes again, bare (no locale prefix) — same reason
# the bare catch-all below exists at all.
${bareDynamicSegmentRules}

# Locale root (e.g. "/en/", "/en") -> the shared build's own root export.
RewriteRule ^[a-z]{2}(-[A-Z]{2})?/?$ /[lang].html [L]

# Everything else under a locale prefix (static/placeholder routes with no
# dynamic segment) -> the shared "[lang]" build. Trailing slash stripped
# from $2 ([^/]/? at the end, not a bare ".*") — a reload/bookmark of e.g.
# "/en/categories/" otherwise appended ".html" after the slash
# ("/[lang]/categories/.html", which doesn't exist) and 404'd, even though
# the no-slash form of the same URL served fine.
RewriteRule ^[a-z]{2}(-[A-Z]{2})?/(.*[^/])/?$ /[lang]/$2.html [L]

# Everything else, bare (no locale prefix, no real file, not one of the
# dynamic-segment routes above) -> the shared "[lang]" build, but only if
# that target actually exists — this is a catch-all ("^(.*)$" matches
# anything, including its own already-rewritten output), so without the -f
# check a genuinely bad URL rewrites to itself forever and Apache 500s with
# "exceeded the limit of 10 internal redirects" instead of a clean 404.
# Must be the last rule: every more specific rule above needs first
# refusal. The client reads the real (unprefixed) locale from the live
# browser URL, same as the dynamic-segment routes above.
RewriteCond %{DOCUMENT_ROOT}/[lang]/$1.html -f
RewriteRule ^(.*)$ /[lang]/$1.html [L]

ErrorDocument 404 /404.html
`;

// SEO=true: Apache doesn't serve pages itself here — it forwards everything
// to the PM2-managed `next start` process on `proxyPort` (mod_proxy), except
// the two asset classes it's faster/simpler to hand back directly: Next's 
// own hashed static chunks (immutable, safe to serve straight off disk) and
// public/'s own static files by extension. _next/data requests still need
// the proxy (they're live JSON, not files) — only _next/static is a real
// on-disk directory.
const proxyContent = `# Apache config for the standalone/VPS build (\`SEO=true\`) — PM2 runs
# \`next start\` on 127.0.0.1:${proxyPort}, Apache reverse-proxies everything
# to it except static assets it can serve straight off disk.
# Generated by scripts/generate-htaccess.mjs (runs via the "prebuild" npm hook,
# port from HTACCESS_PROXY_PORT or \`node scripts/generate-htaccess.mjs <port>\`,
# defaults to ${proxyPort}) — edit that script, not this file directly, it
# gets overwritten on every build.

<IfModule mod_rewrite.c>
    RewriteEngine On
    RewriteBase /

    RewriteRule ^favicon\\.ico$ - [L]

    # Allow SSL certificate verification
    RewriteRule ^.well-known/acme-challenge/(.*) /.well-known/acme-challenge/$1 [L]

    # Serve Next.js STATIC files directly from filesystem (JS/CSS bundles).
    # Only _next/static/ — not all of _next/ (data/image requests still need the proxy).
    RewriteRule ^_next/static/(.*) /.next/static/$1 [L]

    # Proxy Next.js DATA requests to the Node process (required for client-side navigation).
    RewriteRule ^_next/data/(.*) http://127.0.0.1:${proxyPort}/_next/data/$1 [P,L]

    # Serve public/'s own static files directly.
    RewriteCond %{REQUEST_URI} \\.(js|css|svg|jpg|jpeg|png|gif|ico|woff|woff2|ttf|eot|webp|mp4|webm)$
    RewriteRule ^ - [L]

    # Forward everything else to the Node process.
    RewriteRule ^index.html http://127.0.0.1:${proxyPort}/$1 [P]
    RewriteRule ^index.php http://127.0.0.1:${proxyPort}/$1 [P]
    RewriteRule ^/?(.*)$ http://127.0.0.1:${proxyPort}/$1 [P]
</IfModule>
`;

const outputPath = fileURLToPath(new URL("../public/.htaccess", import.meta.url));
writeFileSync(outputPath, seoEnabled ? proxyContent : staticExportContent);
console.log(`Generated ${outputPath} (SEO=${seoEnabled}${seoEnabled ? `, proxy port ${proxyPort}` : ""})`);
